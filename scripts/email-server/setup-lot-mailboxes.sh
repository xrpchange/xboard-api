#!/bin/bash
# Setup Postfix/Dovecot for lot_mailboxes (IMAP chat)
# Run on mail server (xrpchange.site / xdexboard.com) with sudo
# Requires: API DB (xboard) accessible from mail server, postfix-mysql, dovecot-mysql
# See docs/LOT_MAILBOX_AND_IMAP_CHAT.md

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIGS_DIR="${SCRIPT_DIR}/configs"

echo "=== XBoard Lot Mailboxes Setup ==="

# 1. Check packages
for pkg in postfix-mysql dovecot-core dovecot-imapd dovecot-mysql; do
  if ! dpkg -l "$pkg" &>/dev/null; then
    echo "Installing $pkg..."
    apt-get update
    apt-get install -y "$pkg"
  fi
done

# 2. MySQL credentials - set before running or pass as env:
#    LOT_POSTFIX_DB_PASS=... LOT_DOVECOT_DB_PASS=... ./setup-lot-mailboxes.sh
LOT_POSTFIX_DB_USER="${LOT_POSTFIX_DB_USER:-postfix}"
LOT_POSTFIX_DB_PASS="${LOT_POSTFIX_DB_PASS:?Set LOT_POSTFIX_DB_PASS (MySQL password for postfix)}"
LOT_DOVECOT_DB_USER="${LOT_DOVECOT_DB_USER:-dovecot}"
LOT_DOVECOT_DB_PASS="${LOT_DOVECOT_DB_PASS:?Set LOT_DOVECOT_DB_PASS (MySQL password for dovecot)}"
: "${LOT_DB_HOST:=localhost}"
: "${LOT_DB_NAME:=xboard}"

# 3. Postfix MySQL config
POSTFIX_CF="/etc/postfix/mysql-virtual-mailbox-lot.cf"
echo "Creating $POSTFIX_CF..."
cat > "$POSTFIX_CF" << EOF
# Postfix MySQL virtual_mailbox_maps for lot_mailboxes
# Generated by setup-lot-mailboxes.sh
hosts = ${LOT_DB_HOST}
user = ${LOT_POSTFIX_DB_USER}
password = ${LOT_POSTFIX_DB_PASS}
dbname = ${LOT_DB_NAME}
query = SELECT CONCAT('/var/mail/vhosts/', domain, '/', local_part, '/') FROM lot_mailboxes WHERE CONCAT(local_part, '@', domain) = '%s' LIMIT 1
EOF
chmod 640 "$POSTFIX_CF"
chown root:postfix "$POSTFIX_CF"

# 4. Add mysql map to virtual_mailbox_maps in main.cf
MAIN_CF="/etc/postfix/main.cf"
if ! grep -q "mysql:${POSTFIX_CF}" "$MAIN_CF" 2>/dev/null; then
  echo "Adding mysql map to virtual_mailbox_maps in $MAIN_CF..."
  if grep -q "^virtual_mailbox_maps\s*=" "$MAIN_CF"; then
    sed -i "s|^\(virtual_mailbox_maps\s*=\s*\)\(.*\)|\1\2 mysql:${POSTFIX_CF}|" "$MAIN_CF"
  else
    echo "virtual_mailbox_maps = mysql:${POSTFIX_CF}" >> "$MAIN_CF"
  fi
fi

# 5. Dovecot SQL config
DOVECOT_CF="/etc/dovecot/dovecot-sql-lot.conf"
echo "Creating $DOVECOT_CF..."
cat > "$DOVECOT_CF" << EOF
# Dovecot SQL for lot_mailboxes
# Generated by setup-lot-mailboxes.sh
driver = mysql
connect = host=${LOT_DB_HOST} dbname=${LOT_DB_NAME} user=${LOT_DOVECOT_DB_USER} password=${LOT_DOVECOT_DB_PASS}
default_pass_scheme = BLF-CRYPT
password_query = SELECT CONCAT(local_part, '@', domain) AS user, password_hash AS password FROM lot_mailboxes WHERE local_part = '%n' AND domain = '%d'
user_query = SELECT CONCAT(local_part, '@', domain) AS user, 'vmail' AS uid, 'vmail' AS gid, CONCAT('/var/mail/vhosts/', domain, '/', local_part) AS home FROM lot_mailboxes WHERE local_part = '%n' AND domain = '%d'
EOF
chmod 640 "$DOVECOT_CF"
chown root:dovecot "$DOVECOT_CF"

# 6. Include dovecot-sql-lot in dovecot passdb/userdb
DOVECOT_CONF="/etc/dovecot/dovecot.conf"
DOVECOT_CONFD="/etc/dovecot/conf.d"
if [ -d "$DOVECOT_CONFD" ]; then
  INCLUDE_FILE="${DOVECOT_CONFD}/99-lot-mailboxes.conf"
  echo "Creating $INCLUDE_FILE..."
  cat > "$INCLUDE_FILE" << EOF
# Lot mailboxes (IMAP chat) - include in passdb and userdb
# Generated by setup-lot-mailboxes.sh
passdb {
  driver = sql
  args = ${DOVECOT_CF}
}
userdb {
  driver = sql
  args = ${DOVECOT_CF}
}
EOF
else
  echo "WARNING: /etc/dovecot/conf.d not found. Add passdb/userdb manually to dovecot.conf:"
  echo "  passdb { driver = sql; args = ${DOVECOT_CF} }"
  echo "  userdb { driver = sql; args = ${DOVECOT_CF} }"
fi

# 7. Restart services
echo "Restarting Postfix and Dovecot..."
systemctl restart postfix
systemctl restart dovecot

echo "=== Done ==="
echo "Ensure MySQL users exist:"
echo "  CREATE USER IF NOT EXISTS '${LOT_POSTFIX_DB_USER}'@'${LOT_DB_HOST}' IDENTIFIED BY '...';"
echo "  GRANT SELECT ON ${LOT_DB_NAME}.lot_mailboxes TO '${LOT_POSTFIX_DB_USER}'@'${LOT_DB_HOST}';"
echo "  CREATE USER IF NOT EXISTS '${LOT_DOVECOT_DB_USER}'@'${LOT_DB_HOST}' IDENTIFIED BY '...';"
echo "  GRANT SELECT ON ${LOT_DB_NAME}.lot_mailboxes TO '${LOT_DOVECOT_DB_USER}'@'${LOT_DB_HOST}';"
echo "  FLUSH PRIVILEGES;"
